package studio.knit.data

/**
 * Stores attached documents (PDF patterns) as plain files in the app's private storage.
 *
 * Large files are kept out of the database on purpose: Android cannot read a database value
 * larger than about 2 MB in one go, and PDF patterns are often bigger than that.
 */
interface FileStore {
    fun write(id: String, bytes: ByteArray)
    fun read(id: String): ByteArray?
    fun delete(id: String)
    fun exists(id: String): Boolean = read(id) != null
}

/** Keeps files in memory; for tests and previews. */
class InMemoryFileStore : FileStore {
    private val files = HashMap<String, ByteArray>()
    override fun write(id: String, bytes: ByteArray) { files[id] = bytes.copyOf() }
    override fun read(id: String): ByteArray? = files[id]?.copyOf()
    override fun delete(id: String) { files.remove(id) }
    override fun exists(id: String): Boolean = id in files
}

/** Ids are generated by the app; this guards the file system against anything else. */
internal fun safeFileName(id: String): String {
    require(id.isNotEmpty() && id.all { it.isLetterOrDigit() || it == '-' || it == '_' }) { "invalid file id" }
    return id
}
